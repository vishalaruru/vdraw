export interface ParsedDiagramData {
  nodes: { id: string; label: string; shape?: string }[];
  edges: { source: string; target: string; label?: string }[];
}

export function parseXmlBasic(xml: string): ParsedDiagramData {
  const nodes: { id: string; label: string; shape?: string }[] = [];
  const edges: { source: string; target: string; label?: string }[] = [];

  const vertexRegex = /<mxCell[^>]*\bid="([^"]+)"[^>]*\bvalue="([^"]*)"[^>]*\bvertex="1"[^>]*>/g;
  let match;
  while ((match = vertexRegex.exec(xml)) !== null) {
    if (match[1] !== '0' && match[1] !== '1') {
      const cleanLabel = match[2].replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#xa;/g, ' ').replace(/\n/g, ' ');
      nodes.push({ id: match[1], label: cleanLabel || match[1] });
    }
  }

  const edgeRegex = /<mxCell[^>]*\bid="([^"]+)"[^>]*(?:\bvalue="([^"]*)")?[^>]*\bedge="1"[^>]*\bsource="([^"]+)"[^>]*\btarget="([^"]+)"/g;
  while ((match = edgeRegex.exec(xml)) !== null) {
    edges.push({
      source: match[3],
      target: match[4],
      label: match[2] || '',
    });
  }

  return { nodes, edges };
}

export function generateMermaidJs(xml: string): string {
  const { nodes, edges } = parseXmlBasic(xml);
  if (nodes.length === 0) return 'graph TD\n  Empty["(Empty Diagram)"]';

  let code = 'graph TD\n';
  const sanitize = (str: string) => str.replace(/[^a-zA-Z0-9_]/g, '_');

  for (const n of nodes) {
    const safeId = sanitize(n.id);
    const safeLabel = n.label.replace(/"/g, "'");
    code += `  ${safeId}["${safeLabel}"]\n`;
  }

  for (const e of edges) {
    const s = sanitize(e.source);
    const t = sanitize(e.target);
    if (e.label) {
      code += `  ${s} -->|"${e.label}"| ${t}\n`;
    } else {
      code += `  ${s} --> ${t}\n`;
    }
  }

  return code;
}

export function generateTerraform(xml: string): string {
  const { nodes } = parseXmlBasic(xml);
  if (nodes.length === 0) return '# No components detected in diagram';

  let tf = `# Terraform Infrastructure Definition
# Auto-generated by Vdraw Architecture Engine
terraform {
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}

provider "aws" {
  region = "us-east-1"
}

`;

  const sanitizeName = (name: string) =>
    name.toLowerCase().replace(/[^a-z0-9_]/g, '_').slice(0, 32);

  for (const n of nodes) {
    const label = n.label.toLowerCase();
    const id = sanitizeName(n.id || n.label);

    if (label.includes('s3') || label.includes('bucket') || label.includes('storage')) {
      tf += `resource "aws_s3_bucket" "${id}" {\n  bucket = "${id}-vdraw-bucket"\n  tags = {\n    Name = "${n.label}"\n  }\n}\n\n`;
    } else if (label.includes('lambda') || label.includes('function') || label.includes('serverless')) {
      tf += `resource "aws_lambda_function" "${id}" {\n  function_name = "${id}"\n  handler       = "index.handler"\n  runtime       = "nodejs20.x"\n  role          = aws_iam_role.lambda_exec.arn\n}\n\n`;
    } else if (label.includes('dynamo') || label.includes('table')) {
      tf += `resource "aws_dynamodb_table" "${id}" {\n  name         = "${id}"\n  billing_mode = "PAY_PER_REQUEST"\n  hash_key     = "id"\n\n  attribute {\n    name = "id"\n    type = "S"\n  }\n}\n\n`;
    } else if (label.includes('sqs') || label.includes('queue')) {
      tf += `resource "aws_sqs_queue" "${id}" {\n  name = "${id}-queue"\n}\n\n`;
    } else if (label.includes('api') || label.includes('gateway')) {
      tf += `resource "aws_apigatewayv2_api" "${id}" {\n  name          = "${id}-api"\n  protocol_type = "HTTP"\n}\n\n`;
    } else if (label.includes('rds') || label.includes('postgres') || label.includes('sql') || label.includes('db')) {
      tf += `resource "aws_db_instance" "${id}" {\n  allocated_storage   = 20\n  engine              = "postgres"\n  instance_class      = "db.t4g.micro"\n  identifier          = "${id}-db"\n  skip_final_snapshot = true\n}\n\n`;
    } else {
      tf += `# Component: ${n.label}\nresource "aws_instance" "${id}" {\n  ami           = "ami-0c55b159cbfafe1f0"\n  instance_type = "t3.micro"\n  tags = {\n    Name = "${n.label}"\n  }\n}\n\n`;
    }
  }

  return tf;
}

export function generateDockerCompose(xml: string): string {
  const { nodes } = parseXmlBasic(xml);
  if (nodes.length === 0) return '# No components found';

  let dc = `version: '3.8'\nservices:\n`;
  const sanitize = (str: string) => str.toLowerCase().replace(/[^a-z0-9_]/g, '_');

  let portCounter = 8080;
  for (const n of nodes) {
    const name = sanitize(n.label || n.id);
    const l = n.label.toLowerCase();

    if (l.includes('postgres') || l.includes('sql')) {
      dc += `  ${name}:\n    image: postgres:16-alpine\n    environment:\n      POSTGRES_DB: app_db\n      POSTGRES_PASSWORD: secret\n    ports:\n      - "5432:5432"\n\n`;
    } else if (l.includes('redis') || l.includes('cache')) {
      dc += `  ${name}:\n    image: redis:7-alpine\n    ports:\n      - "6379:6379"\n\n`;
    } else if (l.includes('kafka')) {
      dc += `  ${name}:\n    image: bitnami/kafka:latest\n    environment:\n      KAFKA_CFG_NODE_ID: 0\n      KAFKA_CFG_PROCESS_ROLES: controller,broker\n    ports:\n      - "9092:9092"\n\n`;
    } else {
      dc += `  ${name}:\n    build: .\n    container_name: ${name}\n    ports:\n      - "${portCounter}:${portCounter}"\n    environment:\n      NODE_ENV: production\n\n`;
      portCounter++;
    }
  }

  return dc;
}

